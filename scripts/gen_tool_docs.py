"""Generate `docs/tools.md`, the tool reference, from the server itself.

Builds the server with every toolset enabled, deletes allowed and every BookStack feature
available, against a client that never reaches a network, and lists its tools, resources and
prompts. The output is deterministic, so CI can fail when the committed file is stale:

    uv run python scripts/gen_tool_docs.py
    git diff --exit-code docs/tools.md
"""

from __future__ import annotations

import argparse
import asyncio
import json
import sys
from pathlib import Path
from typing import Any

import httpx2

from bookstack_mcp.client import BookStackClient, SystemInfo
from bookstack_mcp.client.version import Features
from bookstack_mcp.config import Settings, Toolset
from bookstack_mcp.server import build_server
from bookstack_mcp.tools import ToolSpec, discover_tools

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "tools.md"
BASE_URL = "https://docs.example.com"
PLACEHOLDER = "unused"
"""Token id and secret for the fake client; nothing is ever sent."""
NEWEST = "v99.12.0"
"""A version past every feature gate, so no tool is hidden."""

HEADER = """\
# Tool reference

<!-- Generated by scripts/gen_tool_docs.py. Do not edit by hand. -->

Generated from the server's own tool list by `uv run python scripts/gen_tool_docs.py`.
Which tools a running server offers depends on the configuration (see the
[README](../README.md#configuration)):

- `BOOKSTACK_MCP_TOOLSETS` picks the toolsets; only `core` is on by default.
- `BOOKSTACK_MCP_READ_ONLY=true` hides every write and destructive tool.
- Destructive tools stay hidden unless `BOOKSTACK_MCP_ALLOW_DELETE=true`.
- Tools that need a newer BookStack than the connected one are hidden.

`bookstack-mcp check` prints the tools a configuration ends up with.
"""


def _fail_transport(request: httpx2.Request) -> httpx2.Response:
    raise RuntimeError("the doc generator must not call BookStack")


def _escape(text: str) -> str:
    """Keep descriptions from turning into HTML tags."""
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _cell(text: str) -> str:
    return _escape(" ".join(text.split())).replace("|", "\\|")


def _code(value: Any) -> str:
    return f"`{json.dumps(value, ensure_ascii=False)}`"


def _min_version(feature: str) -> str:
    """The first BookStack release (YY.MM) with `feature`, or `?` if none up to 99.12."""
    for year in range(20, 100):
        for month in range(1, 13):
            if getattr(Features.from_version((year, month, 0)), feature):
                return f"{year:02d}.{month:02d}"
    return "?"


def _type(schema: dict[str, Any]) -> str:
    """A short type with constraints, such as `integer ≥ 1` or `string (1-255 chars)`."""
    variants = schema.get("anyOf")
    if variants:
        parts = [_type(v) for v in variants if v.get("type") != "null"]
        text = " or ".join(parts) or "null"
        if any(v.get("type") == "null" for v in variants):
            text += " or null"
        return text
    if "enum" in schema:
        return "one of " + ", ".join(_code(v) for v in schema["enum"])
    if "const" in schema:
        return _code(schema["const"])
    kind = schema.get("type", "any")
    if isinstance(kind, list):
        kind = " or ".join(str(k) for k in kind)
    if kind == "array":
        items = schema.get("items", {})
        inner = "object" if items.get("type") == "object" else _type(items)
        kind = f"array of {inner}"
    limits = []
    if "minimum" in schema:
        limits.append(f"≥ {schema['minimum']}")
    if "exclusiveMinimum" in schema:
        limits.append(f"> {schema['exclusiveMinimum']}")
    if "maximum" in schema:
        limits.append(f"≤ {schema['maximum']}")
    if "exclusiveMaximum" in schema:
        limits.append(f"< {schema['exclusiveMaximum']}")
    for low, high, unit in (
        ("minLength", "maxLength", "chars"),
        ("minItems", "maxItems", "items"),
    ):
        if low in schema and high in schema and schema[low] == schema[high]:
            limits.append(f"exactly {schema[low]} {unit}")
        elif low in schema and high in schema:
            limits.append(f"{schema[low]}-{schema[high]} {unit}")
        elif schema.get(low) == 1:
            limits.append("non-empty")
        elif low in schema:
            limits.append(f"at least {schema[low]} {unit}")
        elif high in schema:
            limits.append(f"at most {schema[high]} {unit}")
    if "pattern" in schema:
        limits.append(f"matching `{schema['pattern']}`")
    return f"{kind} ({', '.join(limits)})" if limits else str(kind)


def _resolve(schema: dict[str, Any], defs: dict[str, Any]) -> dict[str, Any]:
    ref = schema.get("$ref")
    if isinstance(ref, str) and ref.startswith("#/$defs/"):
        return _resolve(defs[ref.removeprefix("#/$defs/")], defs)
    resolved = dict(schema)
    if "anyOf" in resolved:
        resolved["anyOf"] = [_resolve(v, defs) for v in resolved["anyOf"]]
    if "items" in resolved:
        resolved["items"] = _resolve(resolved["items"], defs)
    return resolved


def _rows(schema: dict[str, Any], defs: dict[str, Any], prefix: str = "") -> list[str]:
    rows = []
    required = set(schema.get("required", []))
    for name, raw in schema.get("properties", {}).items():
        prop = _resolve(raw, defs)
        default = _code(prop["default"]) if "default" in prop else ""
        rows.append(
            f"| `{prefix}{name}` | {_cell(_type(prop))} | {'yes' if name in required else 'no'} "
            f"| {default} | {_cell(prop.get('description', ''))} |"
        )
        nested = prop
        options = [v for v in prop.get("anyOf", []) if v.get("type") != "null"]
        if len(options) == 1:
            nested = options[0]
        if nested.get("type") == "array":
            nested = nested.get("items", {})
            name += "[]"
        if nested.get("type") == "object" and nested.get("properties"):
            rows.extend(_rows(nested, defs, f"{prefix}{name}."))
    return rows


def _kind(spec: ToolSpec) -> str:
    if spec.destructive:
        return "destructive"
    return "write" if spec.write else "read-only"


def _needs(spec: ToolSpec) -> str:
    return ", ".join(f"BookStack {_min_version(n)}+ (`{n}`)" for n in sorted(spec.needs))


def _tool_section(spec: ToolSpec, tool: Any) -> list[str]:
    lines = [f"## `{spec.name}`", ""]
    if spec.title:
        lines += [f"**{_escape(spec.title)}**", ""]
    facts = [
        f"- Toolset: `{spec.toolset.value}`",
        f"- Kind: {_kind(spec)}{', idempotent' if spec.write and spec.idempotent else ''}",
    ]
    if spec.open_world:
        facts.append("- Reaches beyond BookStack (open world)")
    if spec.needs:
        facts.append(f"- Needs: {_needs(spec)}")
    lines += [*facts, "", _escape((tool.description or "").strip()), ""]
    params = tool.parameters
    rows = _rows(params, params.get("$defs", {}))
    if rows:
        lines += [
            "| Input | Type | Required | Default | Description |",
            "| --- | --- | --- | --- | --- |",
            *rows,
            "",
        ]
    else:
        lines += ["No inputs.", ""]
    return lines


async def render() -> str:
    settings = Settings(
        url=BASE_URL,
        token_id=PLACEHOLDER,
        token_secret=PLACEHOLDER,
        toolsets=frozenset(Toolset),
        read_only=False,
        allow_delete=True,
        _env_file=None,
    )
    client = BookStackClient(
        BASE_URL, PLACEHOLDER, PLACEHOLDER, transport=httpx2.MockTransport(_fail_transport)
    )
    system = SystemInfo(version=NEWEST, instance_id="", app_name="BookStack", base_url=BASE_URL)
    specs = {spec.name: spec for spec in discover_tools()}
    async with client:
        mcp = build_server(settings, client, system, tools=list(specs.values()))
        tools = sorted(await mcp.list_tools(), key=lambda t: t.name)
        resources = sorted(await mcp.list_resources(), key=lambda r: str(r.uri))
        templates = sorted(await mcp.list_resource_templates(), key=lambda r: r.uri_template)
        prompts = sorted(await mcp.list_prompts(), key=lambda p: p.name)
    if {t.name for t in tools} != set(specs):
        raise RuntimeError("some tools are hidden; the generator must list every tool")

    toolsets = [t for t in Toolset if any(s.toolset is t for s in specs.values())]
    lines = [HEADER, "## Tools", ""]
    lines += ["| Tool | Toolset | Kind | Needs |", "| --- | --- | --- | --- |"]
    for tool in tools:
        spec = specs[tool.name]
        lines.append(
            f"| [`{tool.name}`](#{tool.name}) | `{spec.toolset.value}` | {_kind(spec)} "
            f"| {_needs(spec)} |"
        )
    lines += ["", f"Toolsets with tools: {', '.join(f'`{t.value}`' for t in toolsets)}.", ""]
    for tool in tools:
        lines += _tool_section(specs[tool.name], tool)

    lines += ["## Resources", ""]
    if resources or templates:
        for res in resources:
            lines.append(f"- `{res.uri}`: {_cell(res.description or res.name)}")
        for tpl in templates:
            lines.append(f"- `{tpl.uri_template}`: {_cell(tpl.description or tpl.name)}")
    else:
        lines.append("None yet.")
    lines += ["", "## Prompts", ""]
    if prompts:
        for prompt in prompts:
            lines.append(f"- `{prompt.name}`: {_cell(prompt.description or '')}")
    else:
        lines.append("None yet.")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--output", type=Path, default=OUTPUT, help="file to write")
    args = parser.parse_args(argv)
    text = asyncio.run(render())
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")
    print(f"wrote {args.output}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
